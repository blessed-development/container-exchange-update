const product = ({
  id,
  name,
  condition = 'Used',
  size,
  height = 'standard',
  grade,
  base_price,
  rating = 4.8,
  review_count = 80,
  short_description,
  is_bestseller = false,
}) => ({
  id,
  name,
  condition,
  size,
  height,
  grade,
  base_price,
  rating,
  review_count,
  image_url: galleries[id][0],
  inventory_image_url: galleries[id][0],
  image: galleries[id][0],
  gallery_urls: galleries[id].slice(1),
  short_description:
    short_description ||
    (height === 'high_cube'
      ? '40ft High Cube • 9ft 6in High'
      : `${size}ft Standard • 8ft 6in High`),
  is_available: true,
  is_bestseller,
});

