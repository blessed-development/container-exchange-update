import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import locationImageStatus from '../src/data/locationImageStatus.js';
import { inspectLocationImages, printImageReport } from './location-image-utils.mjs';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const statusFile = path.join(projectRoot, 'src', 'data', 'locationImageStatus.js');
const inspections = inspectLocationImages();
const activeStatuses = Object.fromEntries(
  inspections
    .filter(({ location, eligible }) => eligible && (!location.imageReady || locationImageStatus[location.slug]))
    .map(({ location }) => [location.slug, true]),
);

const source = `// Generated by \`npm run locations:activate\`. Do not edit manually.\nexport default ${JSON.stringify(activeStatuses, null, 2)};\n`;
fs.writeFileSync(statusFile, source, 'utf8');

printImageReport(inspections);
const activated = Object.keys(activeStatuses);
const skipped = inspections.filter(({ eligible, location }) => !eligible && !location.imageReady);

console.log(`\nActivated: ${activated.length ? activated.join(', ') : 'none'}`);
console.log(`Skipped: ${skipped.length} location(s) with missing, invalid, or duplicate image paths.`);
console.log('Only install genuine, commercially usable skyline photographs before running this command.');
